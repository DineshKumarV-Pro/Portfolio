        // DOM Elements
        document.addEventListener('DOMContentLoaded', () => {
    const certificatesContainer = document.getElementById('certificates-container');
    const paginationContainer = document.getElementById('pagination');
    const searchInput = document.getElementById('certificate-search');
    const searchSuggestions = document.getElementById('search-suggestions');
    const filterToggle = document.getElementById('filter-toggle');
    const filterDropdown = document.getElementById('filter-dropdown');
    const resetFiltersBtn = document.getElementById('reset-filters');
    const applyFiltersBtn = document.getElementById('apply-filters');

    let currentPage = 1;
    const certificatesPerPage = 9;
    let filteredCertificates = [...certificates];

    // Display certificates function
    function displayCertificates() {
        certificatesContainer.innerHTML = '';

        const startIndex = (currentPage - 1) * certificatesPerPage;
        const endIndex = startIndex + certificatesPerPage;
        const paginatedCertificates = filteredCertificates.slice(startIndex, endIndex);

        if (paginatedCertificates.length === 0) {
            certificatesContainer.innerHTML = 
            `
                <div class="col-span-full text-center py-12">
                    <i class="fas fa-certificate text-4xl text-gray-400 mb-4"></i>
                    <p class="text-gray-600 dark:text-gray-300">No certificates found matching your criteria.</p>
                </div>
            `;
            return;
        }

        paginatedCertificates.forEach(cert => {
            const tagsHTML = cert.tags.map(tag => 
                            '<span class="px-2 py-1 bg-blue-100 dark:bg-blue-900 text-blue-800 dark:text-blue-200 rounded-full text-xs">' + tag + '</span>'
                        ).join('');

            const certificateCard = `
                <div class="bg-white dark:bg-gray-700 rounded-lg overflow-hidden shadow-lg hover:shadow-xl transition-shadow">
                    <div class="w-full">
                        <img src="${cert.image}" alt="${cert.title}" class="w-full h-auto object-contain">
                    </div>
                    <div class="p-6">
                        <h3 class="text-xl font-semibold mb-2">${cert.title}</h3>
                        <p class="text-gray-600 dark:text-gray-300 mb-3">Issued by: ${cert.organization} • ${cert.date}</p>
                        <div class="flex flex-wrap gap-2 mb-4">
                            ${tagsHTML}
                        </div>
                        <a href="${cert.link}" class="inline-flex items-center px-4 py-2 bg-blue-600 hover:bg-blue-700 text-white rounded-lg font-medium transition" target="_blank" rel="noopener">
                            View Certificate <i class="fas fa-external-link-alt ml-2"></i>
                        </a>
                    </div>
                </div>
            `;

            certificatesContainer.innerHTML += certificateCard;
        });
    }

    // Setup pagination
    function setupPagination() {
        paginationContainer.innerHTML = '';
        const pageCount = Math.ceil(filteredCertificates.length / certificatesPerPage);

        if (pageCount <= 1) return;

        // Previous button
        if (currentPage > 1) {
            paginationContainer.innerHTML += `
                <button onclick="changePage(${currentPage - 1})" class="px-3 py-1 border border-gray-300 dark:border-gray-600 rounded hover:bg-gray-100 dark:hover:bg-gray-700" aria-label="Previous Page">
                    <i class="fas fa-chevron-left"></i>
                </button>
            `;
        }

        // Page numbers
        for (let i = 1; i <= pageCount; i++) {
            paginationContainer.innerHTML += `
                <button onclick="changePage(${i})" class="px-3 py-1 ${i === currentPage ? 'bg-blue-600 text-white' : 'border border-gray-300 dark:border-gray-600 hover:bg-gray-100 dark:hover:bg-gray-700'} rounded" aria-label="Page ${i}">
                    ${i}
                </button>
            `;
        }

        // Next button
        if (currentPage < pageCount) {
            paginationContainer.innerHTML += `
                <button onclick="changePage(${currentPage + 1})" class="px-3 py-1 border border-gray-300 dark:border-gray-600 rounded hover:bg-gray-100 dark:hover:bg-gray-700" aria-label="Next Page">
                    <i class="fas fa-chevron-right"></i>
                </button>
            `;
        }
    }

    // Change page function - make global to be used inline onclick
    window.changePage = function(page) {
        currentPage = page;
        displayCertificates();
        setupPagination();
        window.scrollTo({ top: 0, behavior: 'smooth' });
    }

    // Show search suggestions as user types
    function showSuggestions(term) {
        if (term.length === 0) {
            searchSuggestions.classList.add('hidden');
            filteredCertificates = [...certificates];
            displayCertificates();
            setupPagination();
            return;
        }

        let suggestions = [];

        certificates.forEach(cert => {
            if (cert.title.toLowerCase().includes(term)) suggestions.push(cert.title);
            if (cert.organization.toLowerCase().includes(term)) suggestions.push(cert.organization);
            cert.tags.forEach(tag => {
                if (tag.toLowerCase().includes(term)) suggestions.push(tag);
            });
        });

        // Remove duplicates and limit suggestions to 10 max
        const uniqueSuggestions = [...new Set(suggestions)].slice(0, 10);

        if (uniqueSuggestions.length > 0) {
            searchSuggestions.innerHTML = uniqueSuggestions.map(s => `<div class="p-2 hover:bg-gray-100 dark:hover:bg-gray-600 cursor-pointer">${s}</div>`).join('');
            searchSuggestions.classList.remove('hidden');

            // Add click event for suggestion items
            document.querySelectorAll('#search-suggestions div').forEach(item => {
                item.addEventListener('click', () => {
                    searchInput.value = item.textContent;
                    searchSuggestions.classList.add('hidden');
                    filterCertificates();
                });
            });
        } else {
            searchSuggestions.classList.add('hidden');
        }
    }

    // Filter certificates based on search input content
    function filterCertificates() {
        const searchTerm = searchInput.value.toLowerCase();
        if (searchTerm.length === 0) {
            filteredCertificates = [...certificates];
        } else {
            filteredCertificates = certificates.filter(cert => {
                return cert.title.toLowerCase().includes(searchTerm)
                    || cert.organization.toLowerCase().includes(searchTerm)
                    || cert.tags.some(tag => tag.toLowerCase().includes(searchTerm));
            });
        }
        currentPage = 1;
        displayCertificates();
        setupPagination();
    }

    // Setup event listeners for search and filters
    function setupEventListeners() {
        // Show suggestions on input, for any length including 1 or 0
        searchInput.addEventListener('input', () => {
            const term = searchInput.value.toLowerCase();
            showSuggestions(term);
        });

        // Toggle filter dropdown on button click
        filterToggle.addEventListener('click', (e) => {
            e.stopPropagation(); // prevent document click closing it immediately
            filterDropdown.classList.toggle('hidden');
        });

        // Prevent filter dropdown from closing when clicking inside
        filterDropdown.addEventListener('click', (e) => {
            e.stopPropagation();
        });

        // Close dropdown if clicked outside filter toggle or dropdown
        document.addEventListener('click', (e) => {
            if (!filterDropdown.contains(e.target) && !filterToggle.contains(e.target)) {
                filterDropdown.classList.add('hidden');
            }
        });

        // Reset filters: uncheck all, reset list, close dropdown
        resetFiltersBtn.addEventListener('click', () => {
            const checkboxes = filterDropdown.querySelectorAll('input[type="checkbox"]');
            checkboxes.forEach(cb => cb.checked = false);
            filteredCertificates = [...certificates];
            currentPage = 1;
            displayCertificates();
            setupPagination();
            filterDropdown.classList.add('hidden'); // close dropdown after reset
        });

        // Apply filters: filter list, close dropdown
        applyFiltersBtn.addEventListener('click', () => {
            const checkboxes = filterDropdown.querySelectorAll('input[type="checkbox"]:checked');
            const selectedLanguages = [];
            const selectedOrganizations = [];

            // Assuming tags and organizations are known sets:
            const languageTags = ['HTML', 'CSS', 'JavaScript', 'Python', 'C', 'Bootstrap', 'Tailwind', 'Git&GitHub', 'English', 'VScode']; // Adjust as needed
            const organizations = ['Coursera', 'Udemy', 'Infosys | Springboard', 'TCSion']; // Adjust as needed

            checkboxes.forEach(cb => {
                const val = cb.value;
                if (languageTags.includes(val)) selectedLanguages.push(val);
                if (organizations.includes(val)) selectedOrganizations.push(val);
            });

            filteredCertificates = certificates.filter(cert => {
                // Language filter: match any selected lang, or if none selected, always true
                const langMatch = selectedLanguages.length === 0 || selectedLanguages.some(lang => cert.tags.includes(lang));
                // Organization filter: match any selected org, or if none selected, true
                const orgMatch = selectedOrganizations.length === 0 || selectedOrganizations.includes(cert.organization);
                return langMatch && orgMatch;
            });

            currentPage = 1;
            displayCertificates();
            setupPagination();
            filterDropdown.classList.add('hidden'); // close dropdown after apply
        });

    }

    // Initialize
    setupEventListeners();
    displayCertificates();
    setupPagination();
});
